#save a base to save file
def save_base_to_save_file(objects_data, base_identifier, save_slot, base_name=None, progress=None):
    from .save_file import SaveFile
    pending = []
    total = max(1, len(save_slot))
    for index, slot in enumerate(save_slot):
        if progress is not None:
            progress.update(.15 + .40 * index / total,
                            f'Loading save point {index + 1} / {total}')
        save_file = SaveFile(slot)
        save_file.load()
        
        # look for base in save file to see it it exist or not
        in_base = save_file.search_base_with_identifier(base_identifier)
        if in_base is None:
            return
        
        # here update objects list with list provided
        in_base[SaveTranslation.objects] = save_translation.translate_to_obf_data(objects_data)
        
        # update name of base if provided
        if base_name is not None:
            # update name in PersistentPlayerBases
            in_base[SaveTranslation.base_name] = base_name
            
            # update name in ship_ownsership
            if base_identifier.base_type == BaseType.CORVETTE:
                userdata = int(base_identifier.user_data)
                ship_ownsership_element = save_file.get_ship_ownsership_element(userdata)
                ship_ownsership_element[SaveTranslation.base_name] = base_name
        
        pending.append(save_file)
        if progress is not None:
            progress.update(.15 + .40 * (index + 1) / total,
                            f'Prepared save point {index + 1} / {total}')
    # Capture both save points and their metadata before changing either file.
    if progress is not None:
        progress.update(.58, 'Backing up save points')
    generation, _ = backup_policy.snapshot(save_slot, 'export')
    for index, save_file in enumerate(pending):
        if progress is not None:
            progress.update(.64 + .25 * index / total,
                            f'Writing save point {index + 1} / {total}')
        save_file.save()
        if progress is not None:
            progress.update(.64 + .25 * (index + 1) / total,
                            f'Wrote save point {index + 1} / {total}')
    if progress is not None:
        progress.update(.90, 'Finalizing backup')
    backup_policy.finish(generation)
    if progress is not None:
        progress.update(.94, 'Save export finished')
    return "Base/Corvette saved sucessfully"

# The selected save slot's folder within the shared backup root.
def get_backups_folder(save_links):
    backup_folder = backup_policy.directory(save_links)
    backup_folder.mkdir(parents=True, exist_ok=True)
    return str(backup_folder)

# make backup of both save files linked to a save slot
def backup_save_files(save_links):
    generation, copies = backup_policy.snapshot(save_links, 'manual')
    backup_policy.finish(generation)
    return copies
    
# Open backup for each OS type
def open_backup_folder_in_explorer(save_links):
    backup_folder = Path(get_backups_folder(save_links))

    if not backup_folder.exists():
        print(f"Folder does not exist: {backup_folder}")
        return

    if sys.platform == "win32": #windows
        os.startfile(backup_folder)
    elif sys.platform == "darwin":  # macOS
        subprocess.Popen(["open", str(backup_folder)])
    else:  # Linux
        subprocess.Popen(["xdg-open", str(backup_folder)])
    
