class BaseType:
    CORVETTE = "PlayerShipBase"
    BASE = "HomePlanetBase"
    FREIGHTER = "FreighterBase"
    EXTERNAL_BASE = "ExternalPlanetBase"
    SPACESTATION_BASE = "PlayerSpaceStationBase"
